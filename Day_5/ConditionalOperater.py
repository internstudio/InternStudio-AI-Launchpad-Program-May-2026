num1 = 3
num2 = 7

# == Equal to
if num1 == num2:
    print("Both numbers are equal.")
else:
    print("Both numbers are not equal.")


# != Not equal to
if num1 != num2:
    print("Both numbers are not equal.")
else:
    print("Both numbers are equal.")


# > Greater than
if num1 > num2:
    print("Num1 is greater.")
else:
    print("Num1 is not greater.")


# < Less than
if num1 < num2:
    print("Num2 is greater.")
else:
    print("Num2 is not greater.")


# >= Greater than or equal
if num1 >= num2:
    print("Num1 is greater or equal.")
else:
    print("Num1 is not greater or equal.")


# <= Less than or equal
if num1 <= num2:
    print("Num1 is lesser or equal.")
else:
    print("Num1 is not lesser or equal.")