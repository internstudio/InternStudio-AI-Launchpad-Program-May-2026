def multiply(num1,num2,num3):
    multiplication  =num3 * num2 * num1
    return multiplication

def divide(num1,num2,num3):
    division  =num3 / num2 / num1
    return division


mul3 = multiply(3,3,3)
print(mul3)
mul4 = multiply(4,4,4)
print(mul4)
mul5 = multiply(5,5,5)
print(mul5)
mul6 = multiply(6,6,6)
print(mul6)

div3 = divide(3,3,3)
print(div3)
div4 = divide(4,4,4)
print(div4)
div5 = divide(5,5,5)
print(div5)
div6 = divide(6,6,6)
print(div6)